public class Switches {
    public static void main(String[] args) {
        //the above example is for int ,then what about for string?
        String on_or_off = "on";

switch (on_or_off){
	case "on":
		System.out.println("your tv is on");
		break;
	case "off":
		System.out.println("your tv is off");
		break;
	default :
		System.out.println("your tv is on/off");
		
    }
}

}